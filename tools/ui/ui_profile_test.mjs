// Perfiles de autor en la interfaz (libros inventados).
import { createRequire } from "module";
const require = createRequire(process.env.NODE_PATH + "/");
const { chromium } = require("playwright");
const [url, work, shots] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1360, height: 1000 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const waitTaskDone = async () => {
  await page.waitForTimeout(500);
  await page.waitForFunction(() => document.querySelector("#taskbar").hidden === true, null, { timeout: 30000 });
  await page.waitForTimeout(600);
};
await page.goto(url);
await page.waitForSelector("text=Nuevo proyecto");
console.log("selector de perfil al inicio:", await page.locator("#new-profile").count());
await page.fill("#new-epub", `${work}/book.epub`);
await page.fill("#new-folder", `${work}/proyecto`);
await page.click("text=Crear proyecto");
await page.waitForSelector("text=Progreso:");
await page.click("#sidebar >> text=Referencias");
await page.fill("#ref-src", `${work}/ref_en.epub`);
await page.fill("#ref-tgt", `${work}/ref_es.epub`);
await page.fill("#ref-name", "Nets");
await page.click("text=Emparejar");
await waitTaskDone();
await page.fill(".card:has-text('Perfil de autor') input[type=text]", "Autora inventada");
await page.click("button:text-is('Guardar perfil')");
await page.waitForSelector("text=Perfil «Autora inventada» guardado");
await page.evaluate(() => { document.querySelector("#toast").textContent = ""; });
await page.locator(".card:has-text('Perfil de autor')").scrollIntoViewIfNeeded();
await page.screenshot({ path: `${shots}/profile-card.png` });
await page.click("#btn-close-project");
await page.waitForSelector("#new-profile");
console.log("opciones:", await page.locator("#new-profile option").allTextContents());
await page.fill("#new-epub", `${work}/book.epub`);
await page.fill("#new-folder", `${work}/proyecto2`);
await page.selectOption("#new-profile", "autora-inventada");
await page.click("text=Crear proyecto");
await page.waitForSelector("text=Progreso:");
await page.click("#sidebar >> text=Referencias");
await page.waitForSelector("text=Este proyecto usa el perfil «Autora inventada»");
console.log("referencias en el proyecto nuevo:", await page.locator(".card.row h3").allTextContents());
console.log("errores:", errors.length ? errors : "ninguno");
await browser.close();
