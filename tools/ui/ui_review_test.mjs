// Segunda pasada con IA en la interfaz (IA simulada, libro inventado).
import { createRequire } from "module";
const require = createRequire(process.env.NODE_PATH + "/");
const { chromium } = require("playwright");
const [url, work, shots] = process.argv.slice(2);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1360, height: 900 } });
await ctx.grantPermissions(["clipboard-read", "clipboard-write"], { origin: new URL(url).origin });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const clearToasts = () => page.evaluate(() => { document.querySelector("#toast").textContent = ""; });
const waitTaskDone = async () => {
  await page.waitForTimeout(500);
  await page.waitForFunction(() => document.querySelector("#taskbar").hidden === true, null, { timeout: 30000 });
  await page.waitForTimeout(700);
};
await page.goto(url);
await page.waitForSelector("text=Nuevo proyecto");
await page.fill("#new-epub", `${work}/book.epub`);
await page.fill("#new-folder", `${work}/proyecto`);
await page.click("text=Crear proyecto");
await page.waitForSelector("text=Progreso:");
await page.click("#sidebar >> text=Inteligencia artificial");
await page.click("label:has-text('Ollama')");
await page.fill("#ai-model", "modelo-de-prueba");
await page.click("button:text-is('Guardar')");
await page.waitForSelector("text=Ajustes de IA guardados");
await page.click("#sidebar >> text=Capítulos");
await page.click("text=Traducir el siguiente capítulo");
await waitTaskDone();
await page.click("button.link:text-is('The Harbor')");
await page.waitForSelector(".seg");
await page.click("button:text-is('Revisión con IA')");
await page.waitForSelector("#review-panel:not([hidden])");
await page.waitForSelector("text=4 párrafos sin revisar");
await page.click("#review-panel button:text-is('Revisar con IA')");
await waitTaskDone();
await page.waitForSelector(".suggestion");
console.log("panel:", (await page.textContent("#review-panel strong")).trim());
console.log("diff:", (await page.locator(".suggestion .d-del").allTextContents()).join("|"), "→", (await page.locator(".suggestion .d-ins").allTextContents()).join("|"));
await clearToasts();
await page.locator(".suggestion").scrollIntoViewIfNeeded();
await page.screenshot({ path: `${shots}/review-suggestion.png` });
await page.click(".suggestion button:text-is('Aceptar')");
await page.waitForTimeout(400);
console.log("tras aceptar:", (await page.locator(".seg >> nth=1").locator(".tgt").textContent()).slice(0, 60), "| sugerencias:", await page.locator(".suggestion").count());
console.log("panel:", (await page.textContent("#review-panel strong")).trim());

// Modo manual: copiar el bloque de revisión y pegar una respuesta.
await page.click("#sidebar >> text=Inteligencia artificial");
await page.click("label:has-text('Modo manual')");
await page.click("button:text-is('Guardar')");
await page.waitForSelector("text=Ajustes de IA guardados");
await page.click("#sidebar >> text=Capítulos");
await page.click("button.link:text-is('The Harbor')");
await page.waitForSelector("#review-panel");
await page.evaluate(() => { const p = document.querySelector("#review-panel"); p.hidden = false; });
await page.click("#review-panel button:text-is('Revisar todo otra vez')");
await page.waitForSelector("text=4 párrafos sin revisar");
await page.click("button:text-is('Copiar bloque de revisión')");
await page.waitForSelector("text=Bloque copiado: párrafos 0–3");
const clip = await page.evaluate(() => navigator.clipboard.readText());
console.log("portapapeles:", clip.includes("# Segments to review"), clip.includes("ONE single code block"));
await page.fill("#review-panel textarea", '```xml\n<fix id="3"><text>ES ELLA ASINTIÓ.</text><why>Traducir el resto.</why></fix>\n```');
await page.click("#review-panel button:text-is('Solo importar')");
await page.waitForSelector(".suggestion");
console.log("manual:", (await page.textContent("#review-panel strong")).trim());
console.log("errores:", errors.length ? errors : "ninguno");
await browser.close();
