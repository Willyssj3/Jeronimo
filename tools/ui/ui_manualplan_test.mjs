// Modo manual: chat, modelo y plan (libro inventado).
import { createRequire } from "module";
const require = createRequire(process.env.NODE_PATH + "/");
const { chromium } = require("playwright");
const [url, work, shots] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1360, height: 1100 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
await page.goto(url);
await page.waitForSelector("text=Nuevo proyecto");
await page.fill("#new-epub", `${work}/book.epub`);
await page.fill("#new-folder", `${work}/proyecto`);
await page.click("text=Crear proyecto");
await page.waitForSelector("text=Progreso:");
await page.click("#sidebar >> text=Inteligencia artificial");
await page.click("label:has-text('Modo manual')");
await page.click("button:text-is('Guardar')");
await page.waitForSelector("text=Tu chat de IA");
const card = page.locator(".card.sunk:has-text('Tu chat de IA')");
const sel = (label) => card.locator(`.row:has(> label:text-is('${label}')) select`);
console.log("inicial:", await sel("Modelo").inputValue(), await sel("Plan").inputValue(), await sel("Bloque").inputValue());
await sel("Plan").selectOption("gratis");
await page.waitForTimeout(500);
console.log("gratis:", await page.locator(".card.sunk:has-text('Tu chat de IA') .row:has(> label:text-is('Bloque')) select").inputValue());
await page.locator(".card.sunk:has-text('Tu chat de IA') .row:has(> label:text-is('Modelo')) select").selectOption("haiku");
await page.waitForTimeout(500);
console.log("haiku gratis:", await page.locator(".card.sunk:has-text('Tu chat de IA') .row:has(> label:text-is('Bloque')) select").inputValue());
console.log("consejos:", await page.locator(".card.sunk:has-text('Tu chat de IA') .note").count());
await page.waitForSelector("text=Para terminar el libro faltan");
await page.evaluate(() => { document.querySelector("#toast").textContent = ""; });
await page.locator(".card.sunk:has-text('Tu chat de IA')").scrollIntoViewIfNeeded();
await page.screenshot({ path: `${shots}/manual-chat-card.png` });
await page.click("#sidebar >> text=Resumen");
console.log("resumen:", (await page.locator(".steps li >> nth=1").textContent()).replace(/\s+/g, " ").trim());
await page.click("#sidebar >> text=Capítulos");
await page.click("button.link:text-is('The Harbor')");
await page.waitForSelector("#manual-panel:not([hidden])");
console.log("panel:", await page.locator("#manual-panel select").count(), "selectores");
await page.locator("#manual-panel").scrollIntoViewIfNeeded();
await page.screenshot({ path: `${shots}/manual-panel-plan.png` });
console.log("errores:", errors.length ? errors : "ninguno");
await browser.close();
