// Paquete para Proyectos en la interfaz (libro inventado).
import { createRequire } from "module";
const require = createRequire(process.env.NODE_PATH + "/");
const { chromium } = require("playwright");
const [url, work, shots] = process.argv.slice(2);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1360, height: 1000 } });
await ctx.grantPermissions(["clipboard-read", "clipboard-write"], { origin: new URL(url).origin });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const clip = () => page.evaluate(() => navigator.clipboard.readText());
await page.goto(url);
await page.waitForSelector("text=Nuevo proyecto");
await page.fill("#new-epub", `${work}/book.epub`);
await page.fill("#new-folder", `${work}/proyecto`);
await page.click("text=Crear proyecto");
await page.waitForSelector("text=Progreso:");
await page.click("#sidebar >> text=Inteligencia artificial");
await page.click("label:has-text('Modo manual')");
await page.click("button:text-is('Guardar')");
await page.waitForSelector("text=Paquete para Proyectos");
await page.click("button:text-is('Generar paquete')");
await page.waitForSelector("text=Paquete listo");
await page.click("#modal-ok");
await page.waitForTimeout(400);
const instr = await clip();
console.log("instrucciones:", instr.slice(0, 60).replace(/\n/g, " "), "…", instr.includes("# How this project works"));
await page.check("label:has-text('ya subí el paquete') input");
await page.waitForSelector("text=Bloques livianos: cada bloque");
await page.evaluate(() => { document.querySelector("#toast").textContent = ""; });
await page.screenshot({ path: `${shots}/package-card.png` });
await page.click("#sidebar >> text=Capítulos");
await page.click("button.link:text-is('The Harbor')");
await page.waitForSelector("text=Bloques livianos: pega cada bloque");
await page.click("button:text-is('Copiar bloque')");
await page.waitForSelector("text=Bloque copiado: párrafos");
const block = await clip();
console.log("bloque:", block.slice(0, 50), "| largo:", block.length, "| sin guía:", !block.includes("# Style guide"));
console.log("errores:", errors.length ? errors : "ninguno");
await browser.close();
