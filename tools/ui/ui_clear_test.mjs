// Borrar y recuperar la traducción de un capítulo (IA simulada, libro inventado).
import { createRequire } from "module";
const require = createRequire(process.env.NODE_PATH + "/");
const { chromium } = require("playwright");
const [url, work, shots] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const waitTaskDone = async () => {
  await page.waitForTimeout(500);
  await page.waitForFunction(() => document.querySelector("#taskbar").hidden === true, null, { timeout: 30000 });
  await page.waitForTimeout(600);
};
await page.goto(url);
await page.waitForSelector("text=Nuevo proyecto");
await page.fill("#new-epub", `${work}/book.epub`);
await page.fill("#new-folder", `${work}/proyecto`);
await page.click("text=Crear proyecto");
await page.waitForSelector("text=Progreso:");
await page.click("#sidebar >> text=Inteligencia artificial");
await page.click("label:has-text('Ollama')");
await page.fill("#ai-model", "modelo-de-prueba");
await page.click("button:text-is('Guardar')");
await page.waitForSelector("text=Ajustes de IA guardados");
await page.click("#sidebar >> text=Capítulos");
await page.click("text=Traducir el siguiente capítulo");
await waitTaskDone();
await page.evaluate(() => { document.querySelector("#toast").textContent = ""; });
console.log("fila antes:", (await page.locator("tr:has-text('The Harbor') td >> nth=3").textContent()).trim());
await page.screenshot({ path: `${shots}/clear-table.png` });
await page.click("tr:has-text('The Harbor') button[aria-label='Borrar la traducción']");
await page.waitForSelector("#modal-backdrop:not([hidden])");
await page.screenshot({ path: `${shots}/clear-modal.png` });
await page.click("#modal-ok");
await page.waitForSelector("text=Traducción borrada: 4 párrafos");
console.log("fila después:", (await page.locator("tr:has-text('The Harbor') td >> nth=3").textContent()).trim());
await page.click("button.link:text-is('The Harbor')");
await page.waitForSelector("text=Hay una traducción borrada de este capítulo.");
await page.evaluate(() => { document.querySelector("#toast").textContent = ""; });
await page.screenshot({ path: `${shots}/clear-review.png` });
await page.click("button:text-is('Recuperarla')");
await page.waitForSelector("text=Traducción recuperada: 4 párrafos");
console.log("revisión:", await page.locator("text=4 de 4 párrafos traducidos").count() === 1 ? "4 de 4" : "¿?");
console.log("nota visible:", await page.locator("text=Hay una traducción borrada").count());
console.log("errores:", errors.length ? errors : "ninguno");
await browser.close();
